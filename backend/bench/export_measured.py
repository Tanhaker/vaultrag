"""Write frontend/src/lib/measured.ts from the latest result files, so the Trust Center's offline
fallback always shows exactly what was last measured (never hand-typed numbers).

    python -m bench.export_measured   (run from backend/, after pytest and the benchmarks)"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT.parent / "frontend" / "src" / "lib" / "measured.ts"


def load(rel: str):
    p = ROOT / rel
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def main() -> None:
    data = {
        "tests": load("eval/results/pytest.json"),
        "redteam": load("eval/results/redteam.json"),
        "grounding": load("eval/results/grounding.json"),
        "timing": load("eval/results/timing.json"),
        "recall": load("bench/results/recall.json"),
    }
    body = json.dumps(data, indent=2, ensure_ascii=False)
    OUT.write_text(
        "// Generated by backend/bench/export_measured.py from eval/results and bench/results.\n"
        "// Offline fallback for the Trust Center: the live page reads /api/eval/latest instead.\n"
        'import type { EvalResults } from "./api";\n\n'
        f"export const MEASURED = {body} as unknown as EvalResults;\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
